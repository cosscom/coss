/**
 * Downloads every seeded person's and organization's avatar (GitHub's by handle, Unsplash
 * portraits for the rest) into public/avatars, and writes src/lib/avatars.generated.ts mapping
 * handles to the files, so the hub serves every image itself (no third-party image origins in
 * its CSP). Run `bun run avatars:fetch` after changing the seed's people.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { seed } from "../src/lib/seed.ts";

const root = path.resolve(import.meta.dir, "..");
const dir = path.join(root, "public/avatars");
await mkdir(dir, { recursive: true });

const data = seed();
const subjects = [
  ...data.users.map((u) => ({
    handle: u.handle,
    githubHandle: u.githubHandle,
    avatarUrl: u.avatarUrl,
  })),
  ...data.organizations.map((o) => ({
    handle: o.slug,
    githubHandle: o.githubHandle,
    avatarUrl: undefined,
  })),
];

const files: Record<string, string> = {};
for (const subject of subjects) {
  const url = subject.githubHandle
    ? `https://avatars.githubusercontent.com/${subject.githubHandle}?s=512`
    : subject.avatarUrl
      ? `${subject.avatarUrl}?w=512&h=512&fit=crop&crop=faces&fm=jpg&q=80`
      : null;
  if (!url) continue;
  const response = await fetch(url);
  if (!response.ok) {
    console.error(`${subject.handle}: ${response.status} from ${url}`);
    continue;
  }
  const type = response.headers.get("content-type") ?? "";
  const extension = type.includes("png") ? "png" : type.includes("webp") ? "webp" : "jpg";
  const file = `${subject.handle}.${extension}`;
  await writeFile(path.join(dir, file), Buffer.from(await response.arrayBuffer()));
  files[subject.handle] = `/avatars/${file}`;
  console.log(`${subject.handle} → ${file}`);
}

const source = `/* Generated by scripts/fetch-avatars.ts; don't edit. Handle → file under public/. */
export const AVATARS: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;
await writeFile(path.join(root, "src/lib/avatars.generated.ts"), source);
