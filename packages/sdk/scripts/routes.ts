/**
 * Writes `src/core/routes.generated.ts`: the API's path templates, from the committed OpenAPI
 * document, which tracing names spans by. `test/routes.test.ts` fails when it is stale.
 *
 *   bun run openapi:generate   (the root script runs this after the API's)
 */
import { readFileSync, writeFileSync } from "node:fs";

const document = JSON.parse(
  readFileSync(new URL("../../../apps/api/openapi.json", import.meta.url), "utf8"),
) as { paths: Record<string, unknown> };

export function renderRoutes(paths: readonly string[]): string {
  const lines = [...paths].sort().map((path) => `  ${JSON.stringify(path)},`);
  return [
    "// Generated by `bun run --cwd packages/sdk routes:generate` from apps/api/openapi.json. Don't edit.",
    "",
    "/** The API's path templates (`/v1/emails/{id}`): spans are named after the one a call matches. */",
    "export const ROUTES: readonly string[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const target = new URL("../src/core/routes.generated.ts", import.meta.url);
  writeFileSync(target, renderRoutes(Object.keys(document.paths)));
  console.log(`Wrote ${target.pathname}`);
}
