/**
 * The Homebrew formula of a release (`Formula/coss.rb` in the tap), from its `SHA256SUMS`:
 *
 *   bun scripts/homebrew.ts <version> <path to SHA256SUMS> > Formula/coss.rb
 *
 * macOS and glibc Linux, arm64 and x64; completions come from `coss completion <shell>`.
 */
import { readFile } from "node:fs/promises";
import { archiveName, parseChecksums, TARGETS } from "./binaries.ts";

export const REPOSITORY = "cosscom/coss";

/** Where a release's archive is downloaded from (the `coss-cli@<version>` tag's release). */
export function releaseUrl(version: string, file: string, repository: string = REPOSITORY): string {
  return `https://github.com/${repository}/releases/download/coss-cli%40${version}/${file}`;
}

export function renderFormula(options: {
  version: string;
  checksums: Record<string, string>;
  repository?: string;
}): string {
  const { version, checksums } = options;
  if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`Not a version: "${version}".`);
  }
  const block = (os: "darwin" | "linux", arch: "arm64" | "x64") => {
    const target = TARGETS.find((t) => t.os === os && t.arch === arch && !t.libc);
    if (!target) throw new Error(`No ${os}-${arch} target.`);
    const file = archiveName(version, target);
    const sha256 = checksums[file];
    if (!sha256) throw new Error(`SHA256SUMS has no ${file}.`);
    return [
      `    on_${arch === "arm64" ? "arm" : "intel"} do`,
      `      url "${releaseUrl(version, file, options.repository)}"`,
      `      sha256 "${sha256}"`,
      "    end",
    ].join("\n");
  };
  return `# Generated by packages/cli/scripts/homebrew.ts in ${options.repository ?? REPOSITORY} for each
# coss-cli release; edits here are overwritten.
class Coss < Formula
  desc "Command line for coss.com: sign in, send test emails, tail logs, forward webhooks"
  homepage "https://coss.com/docs/cli"
  version "${version}"
  license "MIT"

  on_macos do
${block("darwin", "arm64")}
${block("darwin", "x64")}
  end

  on_linux do
${block("linux", "arm64")}
${block("linux", "x64")}
  end

  def install
    bin.install "coss"
    generate_completions_from_executable(bin/"coss", "completion")
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/coss --version").strip
    assert_match "coss __complete", shell_output("#{bin}/coss completion bash")
  end
end
`;
}

if (import.meta.main) {
  const [version, sums] = process.argv.slice(2);
  if (!version || !sums) {
    console.error("Usage: bun scripts/homebrew.ts <version> <path to SHA256SUMS>");
    process.exit(2);
  }
  process.stdout.write(
    renderFormula({ version, checksums: parseChecksums(await readFile(sums, "utf8")) }),
  );
}
