    /// </summary>
    /// <example><code>
    /// await client.Inboxes.Threads.ListAsync(
    ///     new ListThreadsRequest { InboxId = "inbox_01k7c8m4q2f3e9v6t5r1n0p8yz" }
    /// );
    /// </code></example>
