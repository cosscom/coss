          end
        end

        # A new client secret is tried on a connection before it replaces the old one, and ends an outage if it works.
        # Its client ID can't change: a different app needs its hosts to consent again.
        #
        # @param request_options [Hash]
        # @param params [Coss::Scheduling::OauthApps::Types::UpdateOauthAppRequest]
        # @option request_options [String] :base_url
        # @option request_options [Hash{String => Object}] :additional_headers
        # @option request_options [Hash{String => Object}] :additional_query_parameters
        # @option request_options [Hash{String => Object}] :additional_body_parameters
        # @option request_options [Integer] :timeout_in_seconds
        # @option params [String] :id
        #
        # @example
        #   client.scheduling.oauth_apps.update(
        #     id: "calapp_01kd2m9a0b1c2d3e4f5g6h7j8m",
        #     client_secret: "GOCSPX-abcdefghijklmnopqrstuvwxyz"
        #   )
        #
        # @return [Coss::Types::SchedulingOauthApp]
        def update(request_options: {}, **params)
          params = Coss::Internal::Types::Utils.normalize_keys(params)
          request_data = Coss::Scheduling::OauthApps::Types::UpdateOauthAppRequest.new(params).to_h
          non_body_param_names = %w[id]
          body = request_data.except(*non_body_param_names)

          request = Coss::Internal::JSON::Request.new(
            base_url: request_options[:base_url],
            method: "PATCH",
            path: "v1/scheduling/oauth_apps/#{URI.encode_uri_component(params[:id].to_s)}",
            body: body,
            request_options: request_options
          )
          begin
            response = @client.send(request)
          rescue Net::HTTPRequestTimeout
            raise Coss::Errors::TimeoutError
          end
          code = response.code.to_i
          if code.between?(200, 299)
            (response.body.to_s.empty? ? nil : Coss::Types::SchedulingOauthApp.load(response.body))
          else
            error_class = Coss::Errors::ResponseError.subclass_for_code(code)
            raise error_class.new(response.body, code: code)
          end
        end
      end
    end
  end
end
